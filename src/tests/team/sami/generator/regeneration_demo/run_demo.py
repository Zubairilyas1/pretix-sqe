#!/usr/bin/env python3
"""
Regeneration demo: change two constraints in the OpenAPI spec, regenerate the
test data and report exactly which generated cases changed.

The real spec is NOT modified. A changed copy is written next to this script,
so the demo can be rerun at any time:

    cd pretix-sqe/src
    ../.venv/Scripts/python tests/team/sami/generator/regeneration_demo/run_demo.py

Changes applied (each is a real business decision an organizer could make):
  C1  OrderCreate.code.maxLength   16 -> 12          (shorter order codes)
  C2  QuotaCreate.size.maximum     2147483647 -> 1000 (venue capacity cap)

Outputs (in this folder):
  spec_changed.yaml        the spec with C1 and C2 applied
  test_data_changed.json   generator output for the changed spec
  REGENERATION_REPORT.md   before/after table of every changed case
"""
import json
import sys
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import generate_test_data as gen  # noqa: E402

CHANGES = [
    ("C1", ["components", "schemas", "OrderCreate", "properties", "code", "maxLength"], 12),
    ("C2", ["components", "schemas", "QuotaCreate", "properties", "size", "maximum"], 1000),
]


def _set(doc, path, value):
    node = doc
    for key in path[:-1]:
        node = node[key]
    old = node[path[-1]]
    node[path[-1]] = value
    return old


def _verify():
    """Run the EP/BVA API tests for the changed fields against the new data."""
    import os
    import subprocess
    src = HERE.parents[4]  # .../pretix-sqe/src
    env = dict(os.environ, SQE_TEST_DATA=str(HERE / "test_data_changed.json"))
    out = subprocess.run(
        [sys.executable, "-m", "pytest", "tests/team/sami/api/test_api_ep_bva.py", "-q", "-p", "no:sugar",
         "--tb=no", "-rfX", "-k", "code or size"],
        cwd=src, env=env, capture_output=True, text=True,
    ).stdout
    keep = [ln for ln in out.splitlines() if ln.startswith(("FAILED", "XPASS")) or " passed" in ln]
    return "\n".join(keep)


def main():
    spec = yaml.safe_load(Path(gen.DEFAULT_SPEC).read_text("utf-8"))
    applied = []
    for cid, path, new in CHANGES:
        old = _set(spec, path, new)
        applied.append((cid, ".".join(path[2:]), old, new))

    changed_spec = HERE / "spec_changed.yaml"
    changed_spec.write_text(yaml.safe_dump(spec, sort_keys=False, allow_unicode=True), "utf-8", newline="\n")

    before = gen.build_document(gen.DEFAULT_SPEC)
    after = gen.build_document(changed_spec)
    with open(HERE / "test_data_changed.json", "w", encoding="utf-8", newline="\n") as f:
        json.dump(after, f, indent=2, ensure_ascii=False)
        f.write("\n")

    b = {c["id"]: c for c in before["cases"]}
    a = {c["id"]: c for c in after["cases"]}

    def show(v):
        if isinstance(v, str) and len(v) > 20:
            return f"`{v[:6]}...` (len {len(v)})"
        return f"`{v}`"

    rows = []
    for cid in sorted(set(a) | set(b)):
        x, y = b.get(cid), a.get(cid)
        if x and y and (x["value"], x["expected"]) == (y["value"], y["expected"]):
            continue
        rows.append(
            f"| `{cid}` | {show(x['value']) if x else '—'} | {x['expected'] if x else '—'} "
            f"| {show(y['value']) if y else '—'} | {y['expected'] if y else '—'} |"
        )

    report = [
        "# Regeneration demo: two constraint changes",
        "",
        "Generated by `run_demo.py --verify`; do not edit by hand.",
        "",
        "| Change | Constraint | Before | After |",
        "| :-: | :--- | :-: | :-: |",
        *[f"| {cid} | `{p}` | {o} | {n} |" for cid, p, o, n in applied],
        "",
        f"Spec hash before: `{before['meta']['spec_sha256'][:16]}...`  ",
        f"Spec hash after:  `{after['meta']['spec_sha256'][:16]}...`  ",
        f"Cases before: {before['meta']['total_cases']}, after: {after['meta']['total_cases']}, "
        f"changed: {len(rows)}",
        "",
        "| Case | Value before | Expected before | Value after | Expected after |",
        "| :--- | :-: | :-: | :-: | :-: |",
        *rows,
        "",
        "## Predicted effect on the API tests (if the changed spec were adopted)",
        "",
        "- **C1:** `createOrder.code.BVA.len_max+1` is now 13 characters with expected *reject*. "
        "pretix still accepts up to 16 (`OrderCreateSerializer.code max_length=16`), so this case "
        "**fails**. That is a spec-vs-implementation mismatch the gate would block. "
        "`len_max` (12) and `len_max-1` (11) still pass.",
        "- **C2:** `createQuota.size.BVA.max+1` is now 1001 with expected *reject*. pretix has no "
        "upper limit on quota size, so the request is accepted. These case ids are already tracked "
        "as W-05 (`xfail(strict)`), so they report as *xfailed*, a known defect, not a new "
        "failure. `max` (1000) and `max-1` (999) pass.",
        "- No other case changes, which shows the generator depends only on the constraints, "
        "field by field.",
        "",
    ]
    if "--verify" in sys.argv:
        report += ["## Observed (pytest run on the regenerated data)", "", "```", _verify(), "```", ""]
    (HERE / "REGENERATION_REPORT.md").write_text("\n".join(report), "utf-8", newline="\n")
    print("\n".join(report))


if __name__ == "__main__":
    main()
